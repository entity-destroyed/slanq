from __future__ import annotations

import math

import numpy
import pytest

from slanq.ast_nodes import Literal, Span
from slanq.builtin import _round_half_away, const_value
from slanq.codegen import _Generator, generate_qiskit
from slanq.compiler import compile_source
from slanq.diagnostics import SlanqError
from slanq.ir import ClbitRef, GateOp, InitOp, IRBlock, IRModule, QubitBit, QubitRef


def _generate(module: IRModule) -> str:
    return generate_qiskit(module, source_name="mvp_a.slanq")


def test_output_is_valid_python(mvp_a_ir: IRModule) -> None:
    compile(_generate(mvp_a_ir), "<generated>", "exec")


def test_header_names_the_source(mvp_a_ir: IRModule) -> None:
    first_line = _generate(mvp_a_ir).splitlines()[0]
    assert first_line.startswith("# Generated by Slanq ")
    assert first_line.endswith(" from mvp_a.slanq")


def test_registers_and_circuit_are_declared(mvp_a_ir: IRModule) -> None:
    source = _generate(mvp_a_ir)
    assert 'q = QuantumRegister(1, "q")' in source
    assert 'result = ClassicalRegister(1, "result")' in source
    assert "circuit = QuantumCircuit(q, result)" in source


def test_gate_and_measurement_are_emitted(mvp_a_ir: IRModule) -> None:
    source = _generate(mvp_a_ir)
    assert "circuit.h(q[0])" in source
    assert "circuit.measure(q, result)" in source


def test_function_and_main_guard(mvp_a_ir: IRModule) -> None:
    source = _generate(mvp_a_ir)
    assert "def build_circuit() -> QuantumCircuit:" in source
    assert "return circuit" in source
    assert 'if __name__ == "__main__":' in source


def test_main_guard_forces_utf8_stdout(mvp_a_ir: IRModule) -> None:
    source = _generate(mvp_a_ir)
    assert "import sys" in source
    assert 'sys.stdout.reconfigure(encoding="utf-8")' in source


def test_false_initializer_emits_nothing(mvp_a_ir: IRModule) -> None:
    assert "circuit.x(" not in _generate(mvp_a_ir)


def test_true_initializer_emits_an_x_gate(span: Span) -> None:
    qubit = QubitRef(name="q", size=1)
    module = IRModule(
        qubits=[qubit],
        body=IRBlock(ops=[InitOp(span=span, target=qubit, value=True)]),
    )
    assert "circuit.x(q[0])" in _generate(module)


def test_import_omits_classical_register_when_unused(span: Span) -> None:
    qubit = QubitRef(name="q", size=1)
    module = IRModule(qubits=[qubit], body=IRBlock(ops=[]))
    source = _generate(module)
    assert "from qiskit import QuantumCircuit, QuantumRegister" in source
    assert "ClassicalRegister" not in source


def test_params_precede_targets(span: Span) -> None:
    qubit = QubitRef(name="q", size=1)
    module = IRModule(
        qubits=[qubit],
        body=IRBlock(
            ops=[
                GateOp(
                    span=span,
                    name="RX",
                    targets=[QubitBit(ref=qubit, index=0)],
                    params=[Literal(span=span, value=1.5)],
                )
            ]
        ),
    )
    assert "circuit.rx(1.5, q[0])" in _generate(module)


def test_whole_register_target_is_not_indexed(span: Span) -> None:
    qubit = QubitRef(name="a", size=3)
    module = IRModule(
        qubits=[qubit],
        body=IRBlock(ops=[GateOp(span=span, name="H", targets=[qubit])]),
    )
    assert "circuit.h(a)" in _generate(module)


def test_multi_qubit_constant_sets_the_right_bits(span: Span) -> None:
    """5 is 0b101; the register is little-endian, so bits 0 and 2 are flipped."""
    qubit = QubitRef(name="a", size=3)
    module = IRModule(
        qubits=[qubit],
        body=IRBlock(ops=[InitOp(span=span, target=qubit, value=5)]),
    )
    source = _generate(module)
    assert "circuit.x(a[0])" in source
    assert "circuit.x(a[2])" in source
    assert "circuit.x(a[1])" not in source


def test_index_is_mirrored_for_qiskit(span: Span) -> None:
    """Slanq's q[0] is the most significant qubit, Qiskit's q[0] the least."""
    qubit = QubitRef(name="q", size=3)
    module = IRModule(
        qubits=[qubit],
        body=IRBlock(
            ops=[GateOp(span=span, name="H", targets=[QubitBit(ref=qubit, index=0)])]
        ),
    )
    assert "circuit.h(q[2])" in _generate(module)


def test_single_qubit_register_needs_no_mirroring(span: Span) -> None:
    qubit = QubitRef(name="q", size=1)
    module = IRModule(
        qubits=[qubit],
        body=IRBlock(
            ops=[GateOp(span=span, name="H", targets=[QubitBit(ref=qubit, index=0)])]
        ),
    )
    assert "circuit.h(q[0])" in _generate(module)


def test_generated_module_builds_a_runnable_circuit(mvp_a_ir: IRModule) -> None:
    namespace: dict[str, object] = {}
    exec(_generate(mvp_a_ir), namespace)  # noqa: S102
    circuit = namespace["build_circuit"]()
    assert circuit.num_qubits == 1
    assert circuit.num_clbits == 1


def test_unused_clbit_register_still_declared(span: Span) -> None:
    qubit = QubitRef(name="q", size=1)
    clbit = ClbitRef(name="result", size=1)
    module = IRModule(qubits=[qubit], clbits=[clbit], body=IRBlock(ops=[]))
    assert 'result = ClassicalRegister(1, "result")' in _generate(module)


def _param_source(source: str) -> str:
    """The Python rendering of a single gate parameter written in Slanq."""
    result = compile_source(f"qbool q = false;\nRX({source}, q);\n")
    assert not result.diagnostics.has_errors
    assert result.qiskit_source is not None
    return result.qiskit_source


def test_pi_is_emitted_symbolically() -> None:
    source = _param_source("PI / 4")
    assert "circuit.rx(np.pi / 4, q[0])" in source
    assert "0.785" not in source


def test_numpy_is_imported_only_when_needed() -> None:
    assert "import numpy as np" in _param_source("PI")
    assert "import numpy as np" not in _param_source("1.5")


def test_round_helper_is_emitted_with_slanq_semantics() -> None:
    source = _param_source("round(2.5)")
    assert "circuit.rx(_round(2.5), q[0])" in source
    assert "def _round(value: float) -> int:" in source
    assert "import math" in source


def test_floor_and_ceil_map_to_math() -> None:
    source = _param_source("floor(7 / 2) * ceil(1.2)")
    assert "circuit.rx(math.floor(7 / 2) * math.ceil(1.2), q[0])" in source


@pytest.mark.parametrize(
    "slanq_source",
    [
        "PI / 4", "-PI", "2 ** 3 ** 2", "-2 ** 2", "(-2) ** 2", "2 ** -1",
        "1 - (2 - 3)", "(1 + 2) * 3", "1 + 2 * 3", "-7 % 3", "1 | 2 ^ 3 & 4",
        "(1 | 2) ^ 3", "~5 + 1", "-(1 + 2)", "100 / (2 * 5)", "1 / 2 / 4",
        "floor(PI * 2) + round(1.5)", "(1 - 2) ** 3",
    ],
)
def test_rendered_python_has_the_same_value_as_the_slanq_expression(
    build_ast, slanq_source: str
) -> None:
    """The parenthesising is what makes this hold: Slanq and Python agree on
    precedence only because the grammar was aligned with Python's table."""
    (declaration,) = build_ast(f"float r = {slanq_source};").statements
    rendered = _Generator().expression(declaration.initializer)
    namespace = {"np": numpy, "math": math, "_round": _round_half_away}
    assert eval(rendered, namespace) == const_value(declaration.initializer)  # noqa: S307


def test_unknown_gate_name_fails_loudly(span: Span) -> None:
    """Lower-casing the Slanq name would emit a method Qiskit does not have."""
    qubit = QubitRef(name="q", size=1)
    module = IRModule(
        qubits=[qubit],
        body=IRBlock(ops=[GateOp(span=span, name="phase", targets=[qubit])]),
    )
    with pytest.raises(SlanqError):
        _generate(module)
