from __future__ import annotations

from slanq import __version__
from slanq.ast_nodes import BinaryOp, Call, Expression, Literal, Name, UnaryOp
from slanq.builtin import BUILTIN_CONSTANTS, BUILTIN_FUNCTIONS
from slanq.diagnostics import SlanqError
from slanq.ir import (
    GateOp,
    InitOp,
    IRModule,
    MeasurementOp,
    Op,
    QubitBit,
    QubitOperand,
)

INDENT = " " * 4

BINARY_PRECEDENCE: dict[str, int] = {
    "|": 1, "^": 2, "&": 3,
    "+": 4, "-": 4,
    "*": 5, "/": 5, "%": 5,
    "**": 7,
}
UNARY_PRECEDENCE = 6
ATOM_PRECEDENCE = 99

PYTHON_CONSTANTS: dict[str, str] = {"PI": "np.pi"}

# Lower-casing the Slanq name happens to work for every gate today, but it
# would silently emit `circuit.phase(...)` -- a method Qiskit does not have --
# for anything whose Qiskit spelling differs. An explicit table fails loudly
# instead, the same guard as the transformer's __default__.
QISKIT_METHODS: dict[str, str] = {
    "H": "h", "X": "x", "Y": "y", "Z": "z", "S": "s", "T": "t",
    "Sdg": "sdg", "Tdg": "tdg",
    "RX": "rx", "RY": "ry", "RZ": "rz",
    "CX": "cx", "CY": "cy", "CZ": "cz", "CH": "ch", "SWAP": "swap", "CCX": "ccx",
}

# `round` is not Python's: Slanq rounds a half away from zero, Python to even.
PYTHON_FUNCTIONS: dict[str, str] = {
    "floor": "math.floor",
    "ceil": "math.ceil",
    "round": "_round",
}

ROUND_HELPER = [
    "def _round(value: float) -> int:",
    INDENT + '"""Slanq rounds a half away from zero; Python\'s round() rounds to even."""',
    INDENT + "return math.floor(value + 0.5) if value >= 0 else math.ceil(value - 0.5)",
]


def generate_qiskit(module: IRModule, *, source_name: str) -> str:
    generator = _Generator()
    body = generator.body_lines(module)

    lines = [
        f"# Generated by Slanq {__version__} from {source_name}",
        "# Do not edit: changes are lost on regeneration.",
        "",
    ]
    lines += generator.import_lines(module)
    if generator.needs_round:
        lines += ["", ""] + ROUND_HELPER
    lines += [
        "",
        "",
        "def build_circuit() -> QuantumCircuit:",
    ]
    lines += [INDENT + line for line in body]
    lines += [
        "",
        "",
        'if __name__ == "__main__":',
        # The circuit drawing uses box-drawing characters, which fail on a
        # non-UTF-8 stdout (Windows consoles, redirected output).
        INDENT + 'sys.stdout.reconfigure(encoding="utf-8")',
        INDENT + "print(build_circuit())",
        "",
    ]
    return "\n".join(lines)


class _Generator:
    """Renders one module. The imports depend on what the body turned out to
    need, so the body is rendered first and the header assembled afterwards."""

    def __init__(self) -> None:
        self.needs_numpy = False
        self.needs_math = False
        self.needs_round = False

    def import_lines(self, module: IRModule) -> list[str]:
        standard = ["import sys"]
        if self.needs_math or self.needs_round:
            standard.insert(0, "import math")

        qiskit_names = ["QuantumCircuit", "QuantumRegister"]
        if module.clbits:
            qiskit_names.append("ClassicalRegister")
        third_party = [f"from qiskit import {', '.join(sorted(qiskit_names))}"]
        if self.needs_numpy:
            third_party.insert(0, "import numpy as np")

        return standard + [""] + third_party

    def body_lines(self, module: IRModule) -> list[str]:
        lines = [
            f'{ref.name} = QuantumRegister({ref.size}, "{ref.name}")' for ref in module.qubits
        ]
        lines += [
            f'{ref.name} = ClassicalRegister({ref.size}, "{ref.name}")' for ref in module.clbits
        ]

        registers = [ref.name for ref in module.qubits] + [ref.name for ref in module.clbits]
        lines.append(f"circuit = QuantumCircuit({', '.join(registers)})")

        for op in module.body.ops:
            lines += self.op_lines(op)

        lines.append("return circuit")
        return lines

    def op_lines(self, op: Op) -> list[str]:
        if isinstance(op, InitOp):
            # The register is little-endian, so bit b of the value sits on qubit b.
            # Unlike an explicit index, this needs no mirroring.
            return [
                f"circuit.x({op.target.name}[{bit}])"
                for bit in range(op.target.size)
                if (int(op.value) >> bit) & 1
            ]

        if isinstance(op, GateOp):
            method = QISKIT_METHODS.get(op.name)
            if method is None:
                raise SlanqError(
                    f"internal error: no Qiskit method for the gate '{op.name}'. "
                    "This is a bug in the compiler, not in the source program."
                )
            arguments = [self.expression(param) for param in op.params]
            arguments += [_operand_source(target) for target in op.targets]
            return [f"circuit.{method}({', '.join(arguments)})"]

        if isinstance(op, MeasurementOp):
            return [f"circuit.measure({_operand_source(op.source)}, {op.target.name})"]

        raise NotImplementedError(f"no code generation for {type(op).__name__}")

    def expression(self, expression: Expression) -> str:
        if isinstance(expression, Literal):
            return repr(expression.value)

        if isinstance(expression, Name) and expression.name in BUILTIN_CONSTANTS:
            self.needs_numpy = True
            return PYTHON_CONSTANTS[expression.name]

        if isinstance(expression, UnaryOp) and expression.op in ("-", "~"):
            return f"{expression.op}{self._wrapped(expression.operand, UNARY_PRECEDENCE)}"

        if isinstance(expression, BinaryOp) and expression.op in BINARY_PRECEDENCE:
            return self._binary(expression)

        if isinstance(expression, Call) and expression.callee.name in BUILTIN_FUNCTIONS:
            return self._call(expression)

        raise SlanqError(
            f"internal error: {type(expression).__name__} cannot be rendered as Python. "
            "This is a bug in the compiler, not in the source program."
        )

    def _binary(self, expression: BinaryOp) -> str:
        precedence = BINARY_PRECEDENCE[expression.op]
        right_associative = expression.op == "**"
        left = self._wrapped(expression.left, precedence + int(right_associative))
        right = self._wrapped(expression.right, precedence + int(not right_associative))
        return f"{left} {expression.op} {right}"

    def _call(self, expression: Call) -> str:
        name = expression.callee.name
        if name == "round":
            self.needs_round = True
        else:
            self.needs_math = True
        rendered = ", ".join(self.expression(argument) for argument in expression.args)
        return f"{PYTHON_FUNCTIONS[name]}({rendered})"

    def _wrapped(self, expression: Expression, minimum: int) -> str:
        rendered = self.expression(expression)
        return f"({rendered})" if _precedence(expression) < minimum else rendered


def _precedence(expression: Expression) -> int:
    if isinstance(expression, BinaryOp):
        return BINARY_PRECEDENCE.get(expression.op, ATOM_PRECEDENCE)
    if isinstance(expression, UnaryOp):
        return UNARY_PRECEDENCE
    return ATOM_PRECEDENCE


def _operand_source(operand: QubitOperand) -> str:
    if isinstance(operand, QubitBit):
        return f"{operand.ref.name}[{_qiskit_index(operand)}]"
    return operand.name


def _qiskit_index(bit: QubitBit) -> int:
    """Slanq indexes big-endian -- index 0 is the most significant qubit --
    while the Qiskit register is little-endian."""
    return bit.ref.size - 1 - bit.index


__all__ = ["generate_qiskit"]
